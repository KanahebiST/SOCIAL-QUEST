export function getLevelForXp(xp: number): {
  level: number;
  currentXp: number;
  nextLevelXp: number;
  progressPercent: number;
} {
  let level = 1;
  while (level < LEVEL_THRESHOLDS.length && xp >= LEVEL_THRESHOLDS[level]) {
    level++;
  }

  const currentLevelBase = LEVEL_THRESHOLDS[level - 1];
  const nextLevelTarget = level < LEVEL_THRESHOLDS.length ? LEVEL_THRESHOLDS[level] : currentLevelBase + 10000;
  const xpIntoLevel = xp - currentLevelBase;
  const levelSpan = nextLevelTarget - currentLevelBase;
  const progressPercent = Math.min(100, Math.max(0, Math.floor((xpIntoLevel / levelSpan) * 100)));

  return {
    level,
    currentXp: xp,
    nextLevelXp: nextLevelTarget,
    progressPercent,
  };
}

